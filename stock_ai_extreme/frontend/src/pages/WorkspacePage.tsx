/**
 * Phase 12 — the workspace route (§1).
 *
 * A thin shell: hydrates the persisted store once, resolves a shared permalink
 * (if the URL carries one) and renders the grid. All behaviour lives in the
 * engine, the store and the grid — this page never touches widget internals, so
 * it stays out of the render-critical path.
 */
import { useEffect, useRef, useState } from "react";
import WorkspaceGrid from "../components/workspace/WorkspaceGrid";
import { useWorkspaceStore } from "../store/useWorkspaceStore";
import { readSharedWorkspace, readWorkspaceIdFromLocation } from "../lib/workspace/storage";

export default function WorkspacePage() {
  const ready = useWorkspaceStore((s) => s.ready);
  const hydrate = useWorkspaceStore((s) => s.hydrate);
  const saved = useWorkspaceStore((s) => s.saved);
  const loadSavedWorkspace = useWorkspaceStore((s) => s.loadSavedWorkspace);
  const importSavedWorkspaces = useWorkspaceStore((s) => s.importSavedWorkspaces);
  const [shareNotice, setShareNotice] = useState<string | null>(null);
  /** The link is consumed exactly once, even across a re-render. */
  const linkApplied = useRef(false);

  useEffect(() => {
    if (!ready) void hydrate();
  }, [ready, hydrate]);

  /**
   * Resolve a shared permalink after hydration.
   *
   * Two shapes are supported, both generated by the "Copy link" action:
   *   * `?w=<payload>` — the layout itself, base64url-encoded. This is what
   *     makes a link work on another machine; the workspace is imported and
   *     then opened.
   *   * `?ws=<id>` — a same-device link that resolves to the existing record.
   *
   * Either way the parameters are stripped from the address bar afterwards, so
   * reloading the page does not re-import or re-open it.
   */
  useEffect(() => {
    if (!ready || linkApplied.current) return;
    linkApplied.current = true;

    const shared = readSharedWorkspace();
    if (shared) {
      importSavedWorkspaces([shared]);
      loadSavedWorkspace(shared.id);
      setShareNotice(`Opened the shared workspace “${shared.name}”. It is saved on this device now.`);
      stripShareParams();
      return;
    }

    const id = readWorkspaceIdFromLocation();
    if (!id) return;
    if (saved.some((record) => record.id === id)) {
      loadSavedWorkspace(id);
      setShareNotice("Opened the shared workspace from this link.");
    } else {
      // Honest about the limit: an id-only link cannot carry the layout.
      setShareNotice(
        "This link points at a workspace that is not saved on this device. Ask the sender for a full share link or an exported file."
      );
    }
    stripShareParams();
  }, [ready, saved, loadSavedWorkspace, importSavedWorkspaces]);

  if (!ready) {
    return (
      <main className="ws-page" aria-busy="true">
        <div className="ws-loading">
          <p>Loading workspace…</p>
          <div className="skeleton" style={{ height: 320 }} />
        </div>
      </main>
    );
  }

  return (
    <main className="ws-page">
      <header className="ws-page-head">
        <div>
          <p>Modular financial desktop</p>
          <h1>Workspace</h1>
        </div>
        <span className="ws-page-note">
          Drag headers to move · drag edges to resize · layouts persist per preset
        </span>
      </header>

      {shareNotice && (
        <div className="ws-share-notice" role="status">
          <span>{shareNotice}</span>
          <button
            type="button"
            className="ws-ctl"
            onClick={() => setShareNotice(null)}
            aria-label="Dismiss message"
            title="Dismiss"
          >
            ×
          </button>
        </div>
      )}

      <WorkspaceGrid />
    </main>
  );
}

/** Remove `ws`/`w` from the address bar without navigating. */
function stripShareParams(): void {
  if (typeof window === "undefined") return;
  try {
    const url = new URL(window.location.href);
    if (!url.searchParams.has("ws") && !url.searchParams.has("w")) return;
    url.searchParams.delete("ws");
    url.searchParams.delete("w");
    window.history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
  } catch {
    // A botched URL should never break the page.
  }
}
